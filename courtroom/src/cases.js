/* ---------- сборка ---------- */
function flat(list) {
  const out = [];
  for (const x of list || []) {
    if (Array.isArray(x)) out.push(...flat(x));
    else if (x && typeof x === 'object') out.push(normCmd(x));
  }
  return out;
}
function normCmd(c) {
  for (const k of ['press', 'hitScript', 'then', 'ok', 'fail', 'wrong']) if (Array.isArray(c[k])) c[k] = flat(c[k]);
  if (Array.isArray(c.options)) c.options.forEach(o => { if (Array.isArray(o.then)) o.then = flat(o.then); });
  return c;
}
const CASES = [VIOLIN, BAKERY, GALLERY, KITCHEN];
for (const cs of CASES) {
  cs.script = flat(cs.script);
  for (const id in cs.testimonies) {
    const t = cs.testimonies[id];
    if (t.wrong) t.wrong = flat(t.wrong);
    for (const st of t.statements) {
      st.press = flat(st.press);
      if (st.hitScript) st.hitScript = flat(st.hitScript);
      if (st.hit === undefined) st.hit = null;
    }
  }
}

